def print_order(name, chai_type):
    print(f"{name} ordered {chai_type} chai!")
    
print_order("Aman", "masala")
print_order("Yashi", "ginger")
print_order("Smit", "lemon")
print_order("Yash", "cardamom")

##Output
# Aman ordered masala chai!
# Yashi ordered ginger chai!
# Smit ordered lemon chai!
# Yash ordered cardamom chai!